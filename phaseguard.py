class Reading(BaseModel):
    Timestamp: Optional[str] = None
    Phase1_Current: float
    Phase2_Current: float
    Phase3_Current: float
    Phase1_Voltage: float
    Phase2_Voltage: float
    Phase3_Voltage: float
